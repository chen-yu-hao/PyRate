#!/usr/bin/env python3
"""Run every paper benchmark on both backends and write ``benchmarks/results/``.

Usage::

    python -m benchmarks.run_all            # writes JSON + SUMMARY.md, exits 1 on any failure

Each case runs in a fresh subprocess with the native backend and again with
``PYRATE_DISABLE_NATIVE=1``; the summary reports the worst relative difference
between backends over all numeric check values.
"""

from __future__ import annotations

import importlib
import json
import os
import platform
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmarks" / "results"
CASES = (
    "b02_water_normal_modes",
    "b03_thermochemistry",
    "b04_state_counting",
    "b05_tst_consistency",
    "b06_cvt_convergence",
    "b07_eckart_tunneling",
    "b10_native_parity",
)
NATIVE_ONLY = {"b10_native_parity"}
# Wall-clock timings legitimately differ between runs and backends.
VOLATILE = ("speedup",)


def _child(case: str) -> None:
    from pyrate.native import backend_info

    result = importlib.import_module(f"benchmarks.{case}").run()
    result["backend"] = backend_info()
    print(json.dumps(result, default=float))


def _run(case: str, disable_native: bool) -> dict:
    env = dict(os.environ, PYRATE_DISABLE_NATIVE="1" if disable_native else "0")
    out = subprocess.run([sys.executable, "-m", "benchmarks.run_all", "--child", case],
                         cwd=ROOT, env=env, capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:  # pragma: no cover
        return "unknown"


def _fmt(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def main() -> int:
    if len(sys.argv) == 3 and sys.argv[1] == "--child":
        _child(sys.argv[2])
        return 0

    RESULTS.mkdir(parents=True, exist_ok=True)
    import numpy

    provenance = {
        "commit": os.environ.get("GITHUB_SHA") or _git_commit(),
        "utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "python": platform.python_version(),
        "numpy": numpy.__version__,
        "platform": platform.platform(),
    }
    lines = ["# Paper benchmark results", "",
             f"- commit: `{provenance['commit']}`", f"- run (UTC): {provenance['utc']}",
             f"- Python {provenance['python']}, NumPy {provenance['numpy']}, {provenance['platform']}", "",
             "Generated by `python -m benchmarks.run_all`. Do not edit by hand.", ""]
    failures = 0
    for case in CASES:
        native = _run(case, disable_native=False)
        record = {"provenance": provenance, "native": native}
        parity = None
        if case not in NATIVE_ONLY:
            fallback = _run(case, disable_native=True)
            record["python_fallback"] = fallback
            diffs = []
            for a, b in zip(native["checks"], fallback["checks"]):
                if any(v in a["name"] for v in VOLATILE):
                    continue
                if b["status"] == "fail":
                    failures += 1
                x, y = float(a["value"]), float(b["value"])
                diffs.append(abs(x - y) / max(abs(y), 1e-300) if y != 0 else abs(x))
            parity = max(diffs) if diffs else 0.0
            record["backend_max_rel_diff"] = parity
        (RESULTS / f"{case}.json").write_text(json.dumps(record, indent=2, ensure_ascii=False, default=float) + "\n")

        failures += sum(c["status"] == "fail" for c in native["checks"])
        lines += [f"## {case}: {native['title']}", ""]
        if parity is not None:
            lines += [f"Native backend `{native['backend']['backend']}`; worst C++ vs Python difference "
                      f"over check values: {parity:.2e}.", ""]
        lines += ["| status | check | value | threshold |", "|---|---|---|---|"]
        for c in native["checks"]:
            mark = {"pass": "✅", "fail": "❌", "info": "ℹ️"}[c["status"]]
            lines.append(f"| {mark} | {c['name'].replace('|', chr(92) + '|')} | {_fmt(c['value'])} | {_fmt(c['threshold'])} |")
        lines += ["", "References: " + "; ".join(native["references"]) if native["references"] else "", ""]
        print(f"{case}: {sum(c['status'] == 'fail' for c in native['checks'])} failing check(s)")

    lines.insert(6, f"**Overall: {'all checks passed' if failures == 0 else f'{failures} failing check(s)'}**\n")
    (RESULTS / "SUMMARY.md").write_text("\n".join(lines) + "\n")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
